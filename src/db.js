async function applyIndexes(driver) {
  const parts = String(schemaIndexSql())
    .split(/;\s*(?:\n|$)/)
    .map((s) => s.trim())
    .filter(Boolean);
  for (const part of parts) {
    try {
      await driver.exec(part);
    } catch (err) {
      console.warn('[db] index migration skipped:', err.message);
    }
  }
}

async function createDbFromDriver(driver) {
  await driver.exec(schemaSql(driver.dialect));
  await migrateSchema(driver);
  await applyIndexes(driver);
  return buildApi(driver);
}

async function createDb(dbPath) {
  const envUrl = process.env.DATABASE_URL;
  let driver;
  if (isPostgresUrl(dbPath)) {
    driver = createPostgresDriver(dbPath);
  } else if (dbPath && dbPath !== envUrl) {
    driver = createSqliteDriver(dbPath);
  } else if (envUrl && isPostgresUrl(envUrl)) {
    driver = createPostgresDriver(envUrl);
  } else {
    driver = createSqliteDriver(dbPath || './data/rona-insta.db');
  }
  return createDbFromDriver(driver);
}

