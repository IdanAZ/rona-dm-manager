function nowSql() {
  return new Date().toISOString().replace('T', ' ').slice(0, 19);
}

function isPostgresUrl(value) {
  return typeof value === 'string' && /^(postgres(?:ql)?:\/\/)/i.test(value.trim());
}

function toPgPlaceholders(sql) {
  let i = 0;
  return String(sql).replace(/\?/g, () => `$${++i}`);
}

function rewriteInsertIgnore(sql, dialect) {
  if (dialect !== 'postgres') return sql;
  if (!/^\s*insert\s+or\s+ignore\s+into/i.test(sql)) return sql;
  return sql.replace(/^\s*insert\s+or\s+ignore\s+into/i, 'INSERT INTO') + ' ON CONFLICT DO NOTHING';
}

function preparePostgresRun(sql) {
  const rewritten = rewriteInsertIgnore(sql, 'postgres');
  const text = toPgPlaceholders(rewritten);
  const needsId =
    /^\s*insert\s+into\s+(users|accounts|automations|recipients|outbound_log)\b/i.test(rewritten) &&
    !/returning\b/i.test(rewritten);
  return needsId ? `${text.replace(/;?\s*$/, '')} RETURNING id` : text;
}


