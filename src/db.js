function parseTs(value) {
  if (!value) return NaN;
  const s = String(value);
  const t = Date.parse(s.includes('T') ? s : s.replace(' ', 'T') + 'Z');
  return t;
}

function createSqliteDriver(dbPath) {
  if (dbPath && dbPath !== ':memory:') {
    fs.mkdirSync(path.dirname(path.resolve(dbPath)), { recursive: true });
  }
  const db = new DatabaseSync(dbPath || ':memory:');
  db.exec('PRAGMA journal_mode = WAL;');
  db.exec('PRAGMA foreign_keys = ON;');
  return {
    dialect: 'sqlite',
    async exec(sql) {
      db.exec(sql);
    },
    async run(sql, params = []) {
      const r = db.prepare(sql).run(...params);
      return { lastId: r.lastInsertRowid, changes: r.changes };
    },
    async get(sql, params = []) {
      return db.prepare(sql).get(...params);
    },
    async all(sql, params = []) {
      return db.prepare(sql).all(...params);
    },
    async close() {
      db.close();
    },
    async listAccountColumns() {
      return this.listColumns('accounts');
    },
    async listColumns(table) {
      if (!/^[a-z_]+$/.test(table)) throw new Error('invalid table');
      return db.prepare(`PRAGMA table_info(${table})`).all().map((c) => c.name);
    },
  };
}

function shouldUseSsl(connectionString) {
  if (/sslmode=disable/i.test(connectionString)) return false;
  if (String(process.env.PGSSLMODE || '').toLowerCase() === 'disable') return false;
  if (/sslmode=require|render\.com|neon\.tech|supabase\.co|amazonaws\.com/i.test(connectionString)) return true;
  return process.env.NODE_ENV === 'production';
}

function createPostgresDriver(connectionString) {
  const { Pool } = require('pg');
  const pool = new Pool({
    connectionString,
    ssl: shouldUseSsl(connectionString) ? { rejectUnauthorized: false } : false,
    max: 5,
  });
  return {
    dialect: 'postgres',
    async exec(sql) {
      const parts = String(sql)
        .split(/;\s*(?:\n|$)/)
        .map((s) => s.trim())
        .filter(Boolean);
      for (const part of parts) {
        await pool.query(part);
      }
    },
    async run(sql, params = []) {
      const finalSql = preparePostgresRun(sql);
      const res = await pool.query(finalSql, params);
      return { lastId: res.rows[0] ? res.rows[0].id : undefined, changes: res.rowCount };
    },
    async get(sql, params = []) {
      const res = await pool.query(toPgPlaceholders(sql), params);
      return res.rows[0];
    },
    async all(sql, params = []) {
      const res = await pool.query(toPgPlaceholders(sql), params);
      return res.rows;
    },
    async close() {
      await pool.end();
    },
    async listAccountColumns() {
      return this.listColumns('accounts');
    },
    async listColumns(table) {
      if (!/^[a-z_]+$/.test(table)) throw new Error('invalid table');
      const res = await pool.query(
        `SELECT column_name FROM information_schema.columns
         WHERE table_schema = current_schema() AND table_name = $1`,
        [table]
      );
      return res.rows.map((r) => String(r.column_name));
    },
  };
}

async function addColumnIfMissing(driver, table, name, typ) {
  const cols = new Set(await driver.listColumns(table));
  if (cols.has(name)) return;
  const suffix = driver.dialect === 'postgres' ? 'IF NOT EXISTS ' : '';
  await driver.exec(`ALTER TABLE ${table} ADD COLUMN ${suffix}${name} ${typ}`);
}

async function migrateColumns(driver) {
  const cols = new Set(await driver.listAccountColumns());
  for (const [name, typ] of Object.entries(ACCOUNT_EXTRA_COLUMNS)) {
    if (cols.has(name)) continue;
    const suffix = driver.dialect === 'postgres' ? 'IF NOT EXISTS ' : '';
    await driver.exec(`ALTER TABLE accounts ADD COLUMN ${suffix}${name} ${typ}`);
  }
}

