const { test, describe } = require('node:test');
const assert = require('node:assert/strict');
const {
  isPostgresUrl,
  toPgPlaceholders,
  rewriteInsertIgnore,
  preparePostgresRun,
  schemaSql,
  createDb,
  createDbFromDriver,
  nowSql,
} = require('../src/db');
const { createInstagramClient } = require('../src/services/instagram');
const { createEngine } = require('../src/services/engine');
const { seedDemoAutomation } = require('../src/services/seed');
const { processPayload, mockCommentPayload } = require('../src/routes/webhooks');

describe('postgres SQL helpers', () => {
  test('detects postgres URLs and ignores sqlite paths', () => {
    assert.equal(isPostgresUrl('postgres://u:p@localhost:5432/db'), true);
    assert.equal(isPostgresUrl('postgresql://u:p@localhost/db'), true);
    assert.equal(isPostgresUrl(':memory:'), false);
    assert.equal(isPostgresUrl('./data/rona-insta.db'), false);
    assert.equal(isPostgresUrl(undefined), false);
  });

  test('rewrites ? placeholders and INSERT OR IGNORE for postgres', () => {
    assert.equal(
      toPgPlaceholders('SELECT * FROM accounts WHERE user_id = ? AND ig_user_id = ?'),
      'SELECT * FROM accounts WHERE user_id = $1 AND ig_user_id = $2'
    );
    assert.equal(
      rewriteInsertIgnore(
        'INSERT OR IGNORE INTO processed_comments (comment_id, account_id, automation_id, reason) VALUES (?, ?, ?, ?)',
        'postgres'
      ),
      'INSERT INTO processed_comments (comment_id, account_id, automation_id, reason) VALUES (?, ?, ?, ?) ON CONFLICT DO NOTHING'
    );
    assert.equal(rewriteInsertIgnore('INSERT INTO users DEFAULT VALUES', 'postgres'), 'INSERT INTO users DEFAULT VALUES');
    const withId = preparePostgresRun('INSERT INTO users DEFAULT VALUES');
    assert.match(withId, /RETURNING id/i);
    const ignored = preparePostgresRun(
      'INSERT OR IGNORE INTO processed_comments (comment_id, account_id, automation_id, reason) VALUES (?, ?, ?, ?)'
    );
    assert.match(ignored, /ON CONFLICT DO NOTHING/i);
    assert.doesNotMatch(ignored, /RETURNING id/i);
    const known = preparePostgresRun(
      `INSERT INTO known_media (account_id, media_id, timestamp, permalink, caption, media_type, thumbnail_url)
       VALUES (?, ?, ?, ?, ?, ?, ?)
       ON CONFLICT(account_id, media_id) DO UPDATE SET timestamp = EXCLUDED.timestamp`
    );
    assert.doesNotMatch(known, /RETURNING id/i);
    assert.match(known, /\$7/);
  });

  test('postgres schema uses identity columns and no sqlite datetime()', () => {
    const sql = schemaSql('postgres');
    assert.match(sql, /GENERATED BY DEFAULT AS IDENTITY/);
    assert.doesNotMatch(sql, /AUTOINCREMENT/);
    assert.doesNotMatch(sql, /datetime\('now'\)/);
    assert.match(sql, /TO_CHAR\(NOW\(\)/);
  });

  test('explicit sqlite path is used even if DATABASE_URL is set', async () => {
    const prev = process.env.DATABASE_URL;
    process.env.DATABASE_URL = 'postgres://example.invalid/db';
    try {
      const db = await createDb(':memory:');
      assert.equal(db.dialect, 'sqlite');
      const userId = await db.createUser();
      assert.ok(userId);
      await db.close();
    } finally {
      if (prev === undefined) delete process.env.DATABASE_URL;
      else process.env.DATABASE_URL = prev;
    }
  });
});

function pgliteDriver(client) {
  return {
    dialect: 'postgres',
    async exec(sql) {
      await client.exec(sql);
    },
    async run(sql, params = []) {
      const res = await client.query(preparePostgresRun(sql), params);
      return { lastId: res.rows[0] ? res.rows[0].id : undefined, changes: res.affectedRows ?? res.rowCount ?? res.rows.length };
    },
    async get(sql, params = []) {
      const res = await client.query(toPgPlaceholders(sql), params);
      return res.rows[0];
    },
    async all(sql, params = []) {
      const res = await client.query(toPgPlaceholders(sql), params);
      return res.rows;
    },
    async close() {
      if (typeof client.close === 'function') await client.close();
    },
    async listAccountColumns() {
      return this.listColumns('accounts');
    },
    async listColumns(table) {
      const res = await client.query(
        `SELECT column_name FROM information_schema.columns WHERE table_name = $1`,
        [table]
      );
      return res.rows.map((r) => r.column_name);
    },
  };
}

async function smokeAgainst(db) {
  const config = {
    mockMode: true,
    appUrl: 'http://localhost:3000',
    followCheckMode: 'stub',
    meta: { apiVersion: 'v23.0', appId: '', appSecret: '', scopes: [] },
  };
  const instagram = createInstagramClient({ config, db });
  const engine = createEngine({ db, instagram, config });
  const userId = await db.createUser();
  const account = await db.upsertAccount({
    userId,
    igUserId: 'pg_ig_rona',
    username: 'rona_demo',
    name: 'רונה',
    accessToken: 'mock-token',
    accountType: 'MEDIA_CREATOR',
  });
  const auto = await seedDemoAutomation(db, account.id);
  const results = await processPayload(
    mockCommentPayload({
      igUserId: account.ig_user_id,
      commentId: 'c_pg_1',
      text: 'הכנה',
      mediaId: auto.media_id,
      fromId: 'igsid_pg',
      fromUsername: 'dana',
      isFollower: true,
    }),
    { db, engine }
  );
  assert.equal(results[0].ok, true);
  const recs = await db.listRecipients(auto.id);
  assert.equal(recs.length, 1);
  const metrics = await db.getAutomationMetrics(auto.id);
  assert.equal(Number(metrics.total_sends), 1);

  await db.markCommentProcessed({
    commentId: 'c_pg_1',
    accountId: account.id,
    reason: 'dup-check',
  });
  assert.equal(await db.isCommentProcessed('c_pg_1'), true);

  await db.upsertKnownMedia(account.id, { id: 'm1', caption: 'x', timestamp: nowSql() });
  await db.upsertKnownMedia(account.id, { id: 'm1', caption: 'y', timestamp: nowSql() });
  assert.equal(await db.knownMediaCount(account.id), 1);

  const dueNone = await db.listDueFollowups();
  assert.ok(Array.isArray(dueNone));
  return { account, auto };
}

test('postgres smoke: PGlite or DATABASE_URL', async (t) => {
  if (process.env.DATABASE_URL && /^(postgres(?:ql)?:\/\/)/i.test(process.env.DATABASE_URL)) {
    const db = await createDb(process.env.DATABASE_URL);
    assert.equal(db.dialect, 'postgres');
    try {
      await smokeAgainst(db);
    } finally {
      await db.close();
    }
    return;
  }
  let PGlite;
  try {
    ({ PGlite } = require('@electric-sql/pglite'));
  } catch {
    t.skip('No local Postgres and @electric-sql/pglite is not installed; helper SQL was reviewed and unit-tested.');
    return;
  }
  const client = new PGlite();
  const db = await createDbFromDriver(pgliteDriver(client));
  assert.equal(db.dialect, 'postgres');
  try {
    await smokeAgainst(db);
  } finally {
    await db.close();
  }
});
